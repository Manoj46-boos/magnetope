import type { LevelDef } from '@/sim/types';
import type { SkillAtom } from '@/levels/skills';
import type { Measure, PhasePlan } from '@/levels/clockwork';

/**
 * Renders docs/LEVELS.md from the measured rows: one table per biome, one row
 * per level. The columns are the whole premium story — par honesty, the atom
 * table, the clockwork, the native moment, the curve band, the prop budget —
 * and the CI suite parses the same rows back out, so the doc cannot drift.
 */

const BAR = '▁▂▃▄▅▆▇█';
const band = (fall: number): string => BAR[Math.round(((fall - 0.06) / 0.62) * (BAR.length - 1))]!;

const atom = (skill: string | null): string => skill ?? '—';

export function renderLedger(
  levels: readonly LevelDef[],
  atoms: ReadonlyMap<string, SkillAtom>,
  phases: ReadonlyMap<string, PhasePlan>,
  measures: ReadonlyMap<string, Measure>,
): string {
  const biomes = [...new Set(levels.map((l) => l.biome))];
  const out: string[] = [
    '# The level ledger',
    '',
    'Generated by `npm run levels -- --doc` from the shipped levels, their stored routes and their par ghosts. The test suite re-derives every row, so a stale table fails the build. A human balance pass reviews each level before release (the dull-levels-are-bugs rule).',
    '',
    'The columns read: **Par** — the two-star clock; **Author** — the par ghost, the paced author route (R-LD-17: par = author + 20%); **Route** — the planner\'s clear; **Teach / Drill / Exam** — the level\'s skill atom and its bench seat (R-LD-01/09); **Clockwork** — where the beats land as a share of the route (R-LD-07: establish · twist · escalate · resolve); **Native** — the magnet moments the route spends (R-LD-10); **Fall** — the authored difficulty band with the drawn curve (R-LD-16); **Props** — the body budget (R-LD-11).',
    '',
    'The clockwork a climb can promise is ordinal, and CI holds it on every level: the settle ends inside the quiet opening (≤ 0.40), the climax centre of the biggest hops sits past the first quarter and at or after the settle, and the last catch keeps its grip on the end (≥ 0.70) before the summit. Rogers\' encounter fractions — twist near 40%, escalation through 75-90% — remain the audit\'s guidance: the campaign measures its new verbs early (a teach level that demos its verb from the spawn follows the portal triple, R-LD-02) and its big hops mid-climb, and those measured deviations are the pacing notebook the human balance pass retunes from (R-LD-16).',
    '',
  ];

  for (const biome of biomes) {
    const inBiome = levels.filter((l) => l.biome === biome);
    out.push(`## ${biome[0]!.toUpperCase()}${biome.slice(1)}`, '');
    out.push('| Level | Par | Author | Route | Teach | Drill | Exam | Clockwork | Native | Fall | Props |');
    out.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const level of inBiome) {
      const measure = measures.get(level.id)!;
      const row = atoms.get(level.id)!;
      const plan = phases.get(level.id)!;
      const clock = `${plan.establish.toFixed(2)} · ${plan.twist.toFixed(2)} · ${plan.escalate.toFixed(2)} · ${plan.resolve.toFixed(2)}`;
      const native = `${measure.snaps} snap${measure.snaps === 1 ? '' : 's'} + ${measure.launches} launch${measure.launches === 1 ? '' : 'es'}`;
      out.push(
        `| ${level.id} ${level.name} | ${level.parSeconds}s | ${measure.authorSeconds !== null ? `${measure.authorSeconds.toFixed(1)}s` : '—'} | ${measure.clearSeconds.toFixed(1)}s | ` +
          `${atom(row.teaches)} | ${atom(row.practices)} | ${atom(row.examines)} | ${clock} | ${native} | ` +
          `${Math.round(level.fallRateTarget * 100)}% ${band(level.fallRateTarget)} | ${level.props.length}/260 |`,
      );
    }
    out.push('');
  }
  return out.join('\n');
}
