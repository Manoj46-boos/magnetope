import { readFileSync } from 'node:fs';
import { detectTier, type DeviceHints, type QualityTier } from '@/render/quality';

/**
 * The tier map's report generator (R-PE-11). Until the first player-fit test
 * hands us Poki's own device report, the first-frame probe matrix is the map,
 * and this tool renders it from the live probe so the matrix on record is the
 * one the shipped code answers. Once a report exists — a JSON of the platform's
 * per-device rows — the same command reads it back and names the tier
 * distribution the fleet actually plays on, plus the devices that straddle a
 * boundary line, which are the ones a recalibration would move.
 *
 *   npm run tiermap
 *   npm run tiermap -- --report=device-report.json
 */

const arg = (name: string): string | undefined => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];

/** The probe matrix on record: one row per device class the roadmap publishes. */
export const MATRIX: ReadonlyArray<[string, DeviceHints]> = [
  ['desktop, discrete GPU', { hardwareConcurrency: 12, deviceMemory: 8, devicePixelRatio: 1, coarsePointer: false, maxTextureSize: 16384, rendererName: 'NVIDIA GeForce RTX 3060' }],
  ['school Chromebook', { hardwareConcurrency: 4, deviceMemory: 4, devicePixelRatio: 1, coarsePointer: true, maxTextureSize: 8192, rendererName: 'Intel UHD Graphics 600' }],
  ['2021 budget Android (the PRD\'s floor)', { hardwareConcurrency: 8, deviceMemory: 4, devicePixelRatio: 2, coarsePointer: true, maxTextureSize: 4096, rendererName: 'Mali-G52 MC1' }],
  ['2020 mid-range Android', { hardwareConcurrency: 8, deviceMemory: 6, devicePixelRatio: 2, coarsePointer: true, maxTextureSize: 8192, rendererName: 'Adreno (TM) 618' }],
  ['flagship phone', { hardwareConcurrency: 8, deviceMemory: 8, devicePixelRatio: 3, coarsePointer: true, maxTextureSize: 8192, rendererName: 'Adreno (TM) 740' }],
  ['software rendering (the CI stand-in)', { hardwareConcurrency: 8, deviceMemory: 8, devicePixelRatio: 1, coarsePointer: false, maxTextureSize: 8192, rendererName: 'SwiftShader' }],
];

/** The platform's device report rows the oracle accepts, once the first one exists. */
export interface DeviceReportRow {
  gpuString: string;
  cores: number;
  memoryGb?: number;
  devicePixelRatio: number;
  touch: boolean;
  /** Share of players on this device, as a fraction of the report's week. */
  share: number;
}

export interface TierTally {
  tier: QualityTier;
  share: number;
  devices: string[];
}

const rowTier = (row: DeviceReportRow): QualityTier =>
  detectTier({
    hardwareConcurrency: row.cores,
    deviceMemory: row.memoryGb,
    devicePixelRatio: row.devicePixelRatio,
    coarsePointer: row.touch,
    maxTextureSize: 16384,
    rendererName: row.gpuString,
  });

/** Reads a device report into the tier distribution its players actually play on. */
export function tierTally(rows: DeviceReportRow[]): TierTally[] {
  const byTier = new Map<QualityTier, { share: number; devices: string[] }>();
  for (const row of rows) {
    const tier = rowTier(row);
    const bucket = byTier.get(tier) ?? { share: 0, devices: [] };
    bucket.share += row.share;
    bucket.devices.push(row.gpuString);
    byTier.set(tier, bucket);
  }
  return (['high', 'mid', 'low'] as const)
    .filter((tier) => byTier.has(tier))
    .map((tier) => ({ tier, share: byTier.get(tier)!.share, devices: byTier.get(tier)!.devices }));
}

export function renderMatrix(): string {
  const rows = MATRIX.map(([name, hints]) => `| ${name} | \`${hints.rendererName}\` | ${hints.hardwareConcurrency} cores | ${detectTier(hints)} |`).join('\n');
  return [
    '# The tier map',
    '',
    'Generated by `npm run tiermap` from the live first-frame probe. Until Poki\'s own device report exists — the oracle R-PE-11 names — this matrix is the map the roadmap publishes, and the suite holds every row to the shipped `detectTier`.',
    '',
    '| Device | GPU string | Cores | Tier |',
    '| --- | --- | --- | --- |',
    rows,
    '',
    'When the first player-fit test hands over the platform\'s device report, `npm run tiermap -- --report=device-report.json` re-renders this table from the fleet instead: the tier distribution its players actually play on, and the boundary devices a recalibration would move. The monthly ritual re-reads it and moves the probe lines, not the other way round.',
    '',
  ].join('\n');
}

export function renderTally(rows: DeviceReportRow[]): string {
  const tally = tierTally(rows);
  const total = tally.reduce((sum, t) => sum + t.share, 0);
  const table = tally.map((t) => `| ${t.tier} | ${(100 * t.share).toFixed(1)}% | ${t.devices.slice(0, 8).join(', ')} |`).join('\n');
  return [
    '# The tier map, read from the platform\'s own device report',
    '',
    `Generated by \`npm run tiermap -- --report=…\`. ${rows.length} device rows covering ${(100 * total).toFixed(1)}% of the report's week.`,
    '',
    '| Tier | Players | Devices |',
    '| --- | --- | --- |',
    table,
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('tiermap.ts')) {
  const report = arg('report');
  if (report) {
    const rows = JSON.parse(readFileSync(report, 'utf8')) as DeviceReportRow[];
    console.log(renderTally(rows));
  } else {
    console.log(renderMatrix());
  }
}
