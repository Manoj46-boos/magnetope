/**
 * The doc-drift spine's generator (premium PRD W7): renders the five spine docs
 * from the live code — the feel table and the tuning it quotes, the spectacle
 * beats and the ledger's own spacing, the palettes and grades as shipped, the
 * economy as the progression bot replays it, and the telemetry vocabulary the
 * modules actually speak. W8 adds the MAGNO bible from the emotion table; W9
 * adds the audio bible from the score's own tables.
 *
 *   npm run docs    write all five spine docs
 *
 * The suite re-renders every file and compares it byte for byte, so a doc that
 * drifts from the code fails the build. The docs are never edited by hand.
 */

const GENERATOR = 'npm run docs';
const hue = (h: number): string => `${Math.round(h)}°`;
const hsl = ({ h, s, l }: { h: number; s: number; l: number }): string => `${hue(h)} ${Math.round(s)}% ${Math.round(l)}%`;

const esc = (text: string): string => text.replaceAll('|', '\\|');

