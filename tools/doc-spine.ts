export function renderColorScript(): string {
  const out: string[] = [
    '# The colour script',
    '',
    `Generated by \`${GENERATOR}\` from the shipped palettes and grades. The suite re-renders this file and compares it byte for byte, so the script cannot drift from the art (R-AR-05). Reviewed at every art milestone.`,
    '',
    'One committed palette per biome, in HSL as the art bible writes them, with the display-referred grade each biome carries. The temperature journey runs rust and teal at the bottom to cool silence at the top.',
    '',
    '| Biome | Dominant | Accent | Sky top | Horizon | Fog | Sun | Grade (contrast · saturation · bloom) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const biome of BIOME_ORDER) {
    const p = PALETTES[biome];
    const g = GRADES[biome];
    out.push(
      `| ${biome} | ${hsl(p.dominant)} | ${hsl(p.accent)} | ${hsl(p.skyTop)} | ${hsl(p.skyHorizon)} | ${hsl(p.fog)} (${p.fogDensity}) | ${hsl(p.sunColor)} at ${p.sunElevation}° | ${g.contrast} · ${g.saturation} · ${g.bloom} |`,
    );
  }
  out.push(
    '',
    '## The beat treatments',
    '',
    'How each biome dresses the climb\u2019s clockwork — establish, twist, escalate, resolve — in colour the level ledger already measures:',
    '',
    '| Biome | Establish | Twist | Escalate | Resolve |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const biome of BIOME_ORDER) {
    const [a, b, c, d] = BEAT_INTENTS[biome]!;
    out.push(`| ${biome} | ${esc(a)} | ${esc(b)} | ${esc(c)} | ${esc(d)} |`);
  }
  out.push(
    '',
    '## The laws',
    '',
    `- **The poles** — MAGNO\u2019s red north (${'#' + POLE_NORTH.getHexString()}) and blue south (${'#' + POLE_SOUTH.getHexString()}) are the only red-and-blue pair on screen, whatever the biome: magnetism is the game\u2019s identity and it keeps its colours.`,
    `- **The effect palette** — attract reads cyan, repel amber; bright skies take deeper colours with normal blending so the lines never wash out.`,
    `- **The store card\u2019s own grade** — contrast ${CARD_GRADE.contrast}, saturation ${CARD_GRADE.saturation}, bloom ${CARD_GRADE.bloom}: stronger than any biome because the tile is shrunk to a phone row.`,
    `- **Contrast between biomes is total** — the Scrapyard\u2019s burnt orange against Suburbia\u2019s lawn green is a biome shift the player feels in their bones; within a biome the gamut is narrow on purpose.`,
    '',
  );
  return out.join('\n');
}

export function renderEconomy(): string {
  const threeStar = replayEconomy({ stars: 3, assistOff: false });
  const twoStar = replayEconomy({ stars: 2, assistOff: false });
  const oneStar = replayEconomy({ stars: 1, assistOff: false });
  const firstRange = `${scrapForClear(1, true, false).amount}\u2013${scrapForClear(3, true, false).amount}`;
  const replayRange = `${scrapForClear(1, false, false).amount}\u2013${scrapForClear(3, false, false).amount}`;
  const rewardCount = COSMETICS.filter((c) => c.acquire.how === 'reward').length;
  const seasonalCount = COSMETICS.filter((c) => c.acquire.how === 'seasonal').length;
  const scrapShelf = COSMETICS.filter((c) => c.acquire.how === 'scrap').length;
  const out: string[] = [
    '# The economy',
    '',
    `Generated by \`${GENERATOR}\` from the Scrap formula, the cosmetics table and the progression bot\u2019s own replay (\`src/game/economy-replay.ts\`). The suite re-renders this file and compares it byte for byte, and the economy sim replays the schedule the same way the doc tells it (R-EC-07).`,
    '',
    'One currency, one law: Scrap only ever buys cosmetics, so it never gates content. Biomes open on stars alone — the gates are ' +
      BIOME_STAR_GATES.join(' / ') + ` of the ${BIOME_ORDER.length * 14 * 3} on offer.`,
    '',
    '## The schedule',
    '',
    '| Leg | What | How it pays |',
    '| --- | --- | --- |',
    '| Fixed | Per-clear Scrap | a first clear pays ' + firstRange + ' by stars, a replay ' + replayRange + '; playing without the snap assist earns the 5% bonus |',
    '| Fixed | Star stamps | three a level, on the clear card, on the score\u2019s own tonic |',
    '| Variable | Fall grades | the comedy verdict, C to SSS, on the card and in the locker\u2019s requirement paths |',
    '| Variable | Reward looks | ' + rewardCount + ' earned by playing: stars, clears, perfects, a level\u2019s first clear, the best fall grade |',
    '| Variable | The highlight strip | the session\u2019s funniest falls, best first, in memory only |',
    '| Scheduled | Seasonal slots | ' + seasonalCount + ' looks at their season\u2019s price, in season only |',
    '',
    '## The shelf',
    '',
    `| Shelf | Pieces | Price |`,
    `| --- | --- | --- |`,
    `| Scrap | ${scrapShelf} | ${threeStar.lockerPrice} |`,
    `| Seasonal | ${seasonalCount} | ${threeStar.seasonalPrice} |`,
    `| Earned | ${rewardCount} | playing, not Scrap |`,
    '',
    '## The progression bot\u2019s verdict',
    '',
    `The bot clears every level once under a star policy, then replays, buying the shelf in price order — no grade is assumed, so grade-gated looks sit outside its count:`,
    '',
    '| Policy | First pass pays | Shelf | Replay pays | Rounds to finish the shelf |',
    '| --- | --- | --- | --- | --- |',
    `| 3\u2605, assist on | ${threeStar.firstPass} | ${threeStar.lockerPrice} | ${threeStar.replay} | ${threeStar.replayRoundsToFinish} |`,
    `| 2\u2605, assist on | ${twoStar.firstPass} | ${twoStar.lockerPrice} | ${twoStar.replay} | ${twoStar.replayRoundsToFinish} |`,
    `| 1\u2605, assist on | ${oneStar.firstPass} | ${oneStar.lockerPrice} | ${oneStar.replay} | ${oneStar.replayRoundsToFinish} |`,
    '',
    `The three-star first pass covers the shelf on its own; the two-star pass needs a couple of replay rounds; the one-star pass is the honest floor. Cosmetic prices sit on that curve on purpose: the shelf is a collector\u2019s run, never a gate.`,
    '',
  ];
  return out.join('\n');
}

export function renderEvents(): string {
  const out: string[] = [
    '# The event vocabulary',
    '',
    `Generated by \`${GENERATOR}\` from the telemetry module\u2019s own grammar. The suite re-renders this file and compares it byte for byte, checks that every record the code makes is in this table, and replays a real attempt to hold the payloads to the grammar (R-AN-01).`,
    '',
    'Anonymous gameplay telemetry in Poki\u2019s `measure(category, what, action)` shape — nothing identifying, nothing outside the first-party SDK. Positions are bucketed into ' + CELL_SIZE + ' m cells so heatmaps stay coarse and payloads stay small.',
    '',
    '| Category | What | Action payload | Trigger |',
    '| --- | --- | --- | --- |',
    '| level | the level id | `enter` | an attempt begins |',
    '| retry | the level id | the bare gap in ms since the last fall | an attempt begins after a fall |',
    '| fall | the level id | `h=` height `;c=` cell `;g=` grade | the settle after a fall |',
    '| attempt | the level id | `o=` clear/restart/leave `;ms=` run time `;st=` stars `;stick=` `flip=` `snap=` `fall=` counts `;hot=` top flip cells | an attempt ends |',
    '| ending | watched / skipped | seconds spent | the film ends or is skipped |',
    '| session | length | seconds | the queue flushes at a natural stop |',
    '',
    '## The laws',
    '',
    '- **Batched, never streamed** — records queue in memory and flush only at natural stops: never mid-run, never during an ad.',
    '- **The queue is capped** at ' + MAX_QUEUE + ' records; the oldest drop first, never the newest.',
    '- **Every payload is enumerated** — no free text anywhere in the schema (R-AN-03); the fields above are the whole grammar.',
    '- **The ad lifecycle rides the SDK\u2019s own channel** — impressions and accepts are the host\u2019s business, not the page\u2019s.',
    '',
  ];
  return out.join('\n');
}

const DOCS: ReadonlyArray<[string, () => string]> = [
  ['FEEL.md', renderFeel],
  ['SPECTACLE.md', renderSpectacle],
  ['COLOR_SCRIPT.md', renderColorScript],
  ['ECONOMY.md', renderEconomy],
  ['EVENTS.md', renderEvents],
];

if (process.argv[1]?.endsWith('doc-spine.ts')) {
  for (const [name, render] of DOCS) {
    writeFileSync(resolve(import.meta.dirname, `../docs/${name}`), render());
    console.log(`wrote docs/${name}`);
  }
}
