/**
 * The doc-drift spine's generator (premium PRD W7): renders the five spine docs
 * from the live code — the feel table and the tuning it quotes, the spectacle
 * beats and the ledger's own spacing, the palettes and grades as shipped, the
 * economy as the progression bot replays it, and the telemetry vocabulary the
 * modules actually speak.
 *
 *   npm run docs    write all five spine docs
 *
 * The suite re-renders every file and compares it byte for byte, so a doc that
 * drifts from the code fails the build. The docs are never edited by hand.
 */

const GENERATOR = 'npm run docs';
const hue = (h: number): string => `${Math.round(h)}°`;
const hsl = ({ h, s, l }: { h: number; s: number; l: number }): string => `${hue(h)} ${Math.round(s)}% ${Math.round(l)}%`;

const esc = (text: string): string => text.replaceAll('|', '\\|');

export function renderFeel(): string {
  const w = TUNING.windows;
  const row = ({ event, transition, juice, audio, budget }: (typeof FEEL_ROWS)[number]): string =>
    `| ${event} | ${esc(transition)} | ${esc(juice)} | ${esc(audio.join(', ')) || '—'} | ${esc(budget)} |`;
  const out: string[] = [
    '# The feel bible',
    '',
    `Generated by \`${GENERATOR}\` from the feel table in \`src/game/feel-table.ts\` and the tuning, hit-stop and spacing constants it quotes. The suite re-renders this file and compares it byte for byte, so a hand edit or a code change without a re-render fails the build (R-GF-14).`,
    '',
    `Every state transition that carries feel is named with its juice stack, its audio map and what the stack costs. The event names come from the simulation's own vocabulary, so a row for an event the sim never emits fails the compile, and the suite fails the build if the render, game or audio layers listen to an event this table does not carry. Rows that stage nothing say so — silence is a choice the bible keeps visible.`,
    '',
    '## The state machine',
    '',
    'MAGNO lives in five states — airborne, attached, charging, repelled, recovering — and the game in five phases — play, paused, cleared, ending, busy. The transitions below are the ones the player can feel; the rest (bookkeeping, hazard clock, ghost recording) stage nothing by design.',
    '',
    '## The event table',
    '',
    '| Event | Transition | Juice stack | Audio map | Budget |',
    '| --- | --- | --- | --- | --- |',
    ...FEEL_ROWS.map(row),
    '',
    '## The game beats',
    '',
    '| Beat | Transition | Juice stack | Audio map | Budget |',
    '| --- | --- | --- | --- | --- |',
    ...FEEL_GAME_BEATS.map(row),
    '',
    '## The discipline',
    '',
    `The laws the stacks obey, quoted from the code that enforces them:`,
    '',
    `- **The windows** — coyote ${w.coyoteMs} ms, buffer ${w.bufferMs} ms (R-GF-03): both named, both under the 150 ms line. A flip pressed ${w.coyoteMs} ms after leaving a surface still launches; pressed ${w.bufferMs} ms before one arrives it is held until it does.`,
    `- **The hit-stop law** — the freeze holds ${HOLD_MS} ms inside the ${HIT_STOP_BAND_MS[0]}–${HIT_STOP_BAND_MS[1]} ms band, never stacked, at most one per ${MIN_GAP_MS} ms, and reduced motion trades it for a clean cut (R-GF-01/06). Only a full-power release earns it, never inside an input-critical window, never on top of a slow-mo beat.`,
    `- **The spacing ledger** — no two signature beats inside ${(SPECTACLE_SPACING_MS / 1000).toFixed(0)} s (R-SM-06). The scripted beats are recorded, the big-fall slow motion is the beat that yields, and the clear card is the breathing space the rule banks on.`,
    `- **Tier parity** — every timing above is the same on every quality tier; only the ceilings move: ${PROFILES.low.particleCeiling}/${PROFILES.mid.particleCeiling}/${PROFILES.high.particleCeiling} concurrent particles and the animation layer under ${'`'}1.5 ms${'`'} p99 on the mid-tier reference. The freeze, the lunge and the windows never drop with the tier (R-GF-13).`,
    `- **The reduced-motion path** — the freeze, the shake and the dolly all step aside; the cut, the flash and the cards carry the meaning on their own (R-GF-11's law: visual juice carries meaning).`,
    `- **The shake grammar** — one shake source a moment, scaled by impact, never stacked: two shakes back to back read as a fault, not feedback.`,
    '',
  ];
  return out.join('\n');
}

export function renderSpectacle(): string {
  const row = ({ kind, rule, emotion, composition, budget, test }: (typeof SPECTACLE_BEATS)[number]): string =>
    `| ${kind} | ${rule} | ${esc(emotion)} | ${esc(composition)} | ${esc(budget)} | ${test} |`;
  const out: string[] = [
    '# The spectacle table',
    '',
    `Generated by \`${GENERATOR}\` from the beat table in \`src/game/spectacle-table.ts\` and the spacing ledger's own constant. The suite re-renders this file and compares it byte for byte (R-SM-07).`,
    '',
    `Every signature beat is named with the emotion it aims for (the MDA aesthetic it serves), the composition stack it spends, what the stack costs, and the test that holds it. A beat that is not in this table does not fire — and a table row whose test has vanished fails the build.`,
    '',
    '| Beat | Ledger | Emotion | Composition | Budget | Test |',
    '| --- | --- | --- | --- | --- | --- |',
    ...SPECTACLE_BEATS.map(row),
    '',
    '## The spacing law',
    '',
    `No two signature beats inside ${(SPECTACLE_SPACING_MS / 1000).toFixed(0)} seconds of each other (R-SM-06). The scripted beats — the biome establishing shot, the one-time first catch, the ending film — are authored, so the ledger records them rather than gating them. The dynamic beat, the big-fall slow motion, is the one that yields: a fall straight after a staged moment stays at full speed, because two spectacles back to back read as noise. The route linter replays all seventy recorded routes against the delivered timeline and pins the measured reality — tall levels swing more than twelve metres between catches by design, so the bar allows at most two suppressed slow-mos per route while the ledger delivers the twenty-second rule at runtime.`,
    '',
  ];
  return out.join('\n');
}

